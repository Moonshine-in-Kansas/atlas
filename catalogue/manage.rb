# Deterministic reader documentation; this is not a Lean proof checker.
require 'json'
require 'csv'
require 'digest'
require 'zlib'
require 'set'
require_relative 'model_views'
ROOT=File.expand_path('..',__dir__)
Dir.chdir(ROOT)
mode=ARGV.fetch(0,'check')
abort 'Usage: ruby catalogue/manage.rb [refresh|check]' unless %w[refresh check].include?(mode)
def load_json(p)=JSON.parse(File.read(p))
def cell(s)=s.to_s.gsub('|','\\|').gsub(/\s*\n\s*/,' ')
def anchor(e)=e.fetch('id').downcase.tr('.','-')
def label(e)=e.dig('presentation','label') || e.fetch('label')
def count(n)=n.to_s.reverse.scan(/.{1,3}/).join(',').reverse
MATHLIB=JSON.parse(File.read('lake-manifest.json')).fetch('packages').find { |p|p['name']=='mathlib' }.fetch('rev')
def source_link(p,prefix='')
  p.start_with?('.lake/packages/mathlib/') ? 'https://github.com/leanprover-community/mathlib4/blob/'+MATHLIB+'/'+p.delete_prefix('.lake/packages/mathlib/') : prefix+p
end
registry=load_json('catalogue/catalogue.json')
entries=registry.fetch('entries')
raise 'Duplicate catalogue entry' unless entries.map { |e|e['id'] }.uniq.size==entries.size
raise 'Unexpected catalogue scope' unless entries.group_by { |e|e['kind'] }.transform_values(&:size)=={'family'=>16,'exceptional'=>1,'sporadic'=>16}
counts=load_json('catalogue/dependency-counts.json').to_h { |r|[r.fetch('id'),r] }
overlay=load_json('catalogue/realizations.json')
comparison_data=load_json('catalogue/comparisons.json')
comparison_rows=comparison_data.fetch('entries')+comparison_data.fetch('supplements').flat_map { |s|s.fetch('entries') }
model_views=AtlasModelViews::View.new(ROOT)
model_views.render_diagrams(mode)
diagrams={}
entries.each do |e|
  raise 'Incomplete entry in completed catalogue' unless e['proof_status']=='construction_complete'
  e.fetch('roles').each_value do |r|
    p=r.fetch('source')
    raise "Missing source #{p}" unless p.start_with?('.lake/packages/mathlib/') || File.file?(p)
  end
  p=e.fetch('proof_dependencies'); html=File.read(p)
  d=JSON.parse(html[/<script id="data" type="application\/json">(.*?)<\/script>/m,1])
  raise "Wrong order root: #{e['id']}" unless d.dig('roots','order')==e.dig('roles','order','declaration')
  allowed=[e.dig('roles','simple','declaration')]+e.fetch('properties',[]).map { |r|r['declaration'] }
  raise "Wrong simplicity root: #{e['id']}" unless allowed.include?(d.dig('roots','simplicity'))
  d.fetch('source_hashes').each { |p,h|raise "Changed diagram source #{p}" unless Digest::SHA256.file(p).hexdigest==h }
  r=counts.fetch(e['id'])
  raise "Changed line counts #{e['id']}" unless r['intrinsic_lines']==d['intrinsic_lines'] && r['total_lines']==d['total_lines']
  diagrams[e['id']]=d
end
out={}
text=<<~MD
  # A constructive ATLAS of finite simple groups in Lean — Version 1.2 catalogue

  <!-- Generated by catalogue/manage.rb from the maintained registry. -->
  The 33 completed entries comprise 16 families, 16 sporadic constructions and the
  Tits group. They describe explicit models and their stated parameter ranges.
  See [verification status](AUDIT.md), [constructions and identification certificates](catalogue/REALIZATIONS.md)
  and [the comparison theorem](COMPARISON.md). Release acceptance remains pending.

  In the Lie-type rows, q is the base-field size and n is Lie rank:
  Aₙ(q)=PSLₙ₊₁(q), ²Aₙ(q)=PSUₙ₊₁(q). In Aₙ, n is the permutation degree.
  For Cₚ, p is prime. Exact dimension conventions are retained below.
  Open a group name for its construction details and available isomorphism certificates.

  | Group or family | Models | Order | Proven simplicity | Lean files / theorems | Intrinsic lines | Total dependency lines |
  |---|---|---|---|---|---:|---:|
MD
entries.each do |e|
  r=counts.fetch(e['id'])
  text<<"| [#{label(e)}](##{anchor(e)}) | #{model_views.summary(e['id'])} | #{cell(e.dig('presentation','summary_order'))} | #{cell(e.dig('presentation','summary_simplicity'))} | [#{r['files']} / #{r['source_theorems']}](#{e['proof_dependencies']}) | #{count(r['intrinsic_lines'])} | #{count(r['total_lines'])} |\n"
end
text<< <<~MD

  Both line columns count required ATLAS declaration spans for order and simplicity
  together. Intrinsic counts stop at the documented reused-group boundaries; total
  counts include ATLAS prerequisites. Both exclude Lean/mathlib. Rows overlap and
  must not be added. Each diagram lists its exact counted roots; supplementary
  statements below can cover a wider parameter range. The [dated measurements](catalogue/dependency-counts.json) and
  [source binding](verification/release-candidate/DIAGRAM_BINDING.json) are preserved;
  packaging the diagrams is not a new proof check. Download an HTML file to view it.

  All six additional Chevalley constructions are displayed alongside the original
  A/B/C/D/F₄/G₂ models. [Explicit Lean certificates](catalogue/ISOMORPHISMS.md)
  identify the registered A/B/C/D pairs. The G₂ and F₄ comparison scopes are stated
  separately. The table counts and diagrams describe the original default models;
  multiple constructions do not increase the number of families.

MD
entries.each do |e|
  text<<"<a id=\"#{anchor(e)}\"></a>\n\n## #{label(e)}\n\n"
  text<<"Exceptions: #{e['exceptions']}\n\n" unless e.fetch('exceptions','').empty? || e['exceptions']==e['parameters']
  text<<"#{e.dig('presentation','note')}\n\n" if e.dig('presentation','note')
  text<<model_views.detailed(e)
  text<<"\n#{e['recognition']}\n\n"
  text<<"[Compiled principal statements](THEOREM_STATEMENTS.md##{anchor(e)}) · [Proof dependencies](#{e['proof_dependencies']})"
  eid=e['evidence']
  text<<" · [Dated construction evidence](#{registry.fetch('evidence').fetch(eid).fetch('directory')})" if eid
  text<<" · [All construction models](catalogue/REALIZATIONS.md##{anchor(e)})"
  text<<"\n\n"
end
text<<"## Auxiliary groups and covers\n\nThese are separate from the simple-group count.\n\n| Group | Order | Mathematical scope |\n|---|---|---|\n"
registry['auxiliary'].each { |e|text<<"| #{cell(e['label'])} | #{cell(e['order'])} | #{cell(e['construction'])}; #{cell(e['evidence_scope'])} |\n" }
text<<"\n## Isomorphisms and nonisomorphisms\n\nThe [construction and identification guide](catalogue/REALIZATIONS.md) separates\n[comparisons between models](catalogue/REALIZATIONS.md#same-group),\n[exceptional isomorphisms](catalogue/REALIZATIONS.md#between-families), and\n[nonisomorphism by orders or invariants](catalogue/REALIZATIONS.md#remaining-pairs).\nEach result links its Lean statement and verification certificate.\nThe [model-order statements](THEOREM_STATEMENTS.md) and [verification records](AUDIT.md)\nprovide the cardinalities used in the order argument.\n"
out['CATALOGUE.md']=text
out['catalogue/GROUPS.csv']=CSV.generate { |csv|csv<<%w[id label kind models identification_certificates parameters order simplicity];entries.each { |e|csv<<[e['id'],label(e),e['kind'],model_views.models.fetch(e['id']).map { |m|model_views.short_label(m) }.join('; '),model_views.edges(e['id']).map { |c|c.dig('witness','declaration') }.join('; '),e['parameters'],e.dig('presentation','summary_order'),e.dig('presentation','summary_simplicity')] } }

real=model_views.comparison_guide
out['catalogue/REALIZATIONS.md']=real

cmp=model_views.comparison_interfaces
out['catalogue/COMPARISONS.md']=cmp

# Recover verbatim compiled principal signatures, never synthesize them from source.
wanted=(entries.flat_map { |e|%w[order simple].map { |r|e.dig('roles',r,'declaration') } }+model_views.extra_statement_names+model_views.supplemental_statement_names).to_set
statements={}
current=load_json('verification/current.json')
audit=current.fetch('supplemental_cache_audit')
bundle_path=audit.fetch('directory')+'/BUNDLE.json'
raise 'Changed compiled-statement bundle' unless Digest::SHA256.file(bundle_path).hexdigest==audit.fetch('bundle_sha256')
log_name='full-dependency-extraction.log.gz'
logs=[audit.fetch('directory')+'/'+log_name]
raise 'Changed compiled-statement log' unless Digest::SHA256.file(logs.first).hexdigest==load_json(bundle_path).fetch('files').fetch(log_name)
logs.each do |p|
  io=p.end_with?('.gz') ? Zlib::GzipReader.open(p) : File.open(p)
  name=nil;lines=[]
  flush=lambda { statements[name]||={text:lines.join,path:p} if name && !lines.empty? }
  io.each_line do |l|
    if l.match?(/\A(?:STATEMENT|DEFINITION|SHARED EXTRACTION|AXIOMS)\b/)
      flush.call;lines=[]
      n=l[/\ASTATEMENT (\S+) SOURCE /,1]
      name=wanted.include?(n) ? n : nil
    elsif name
      lines<<l
    end
  end
  flush.call;io.close
end
missing=wanted-statements.keys.to_set
raise "Missing compiled signatures: #{missing.to_a.join(', ')}" unless missing.empty?
sig="# Principal compiled theorem statements\n\nThese signatures are copied verbatim from the source-bound 26 October compiled\naudit, with implicit parameters and instances visible. See [verification status](AUDIT.md)\nfor the distinction between this cached-artifact audit and a fresh proof rebuild.\n\n"
entries.each do |e|
  sig<<"<a id=\"#{anchor(e)}\"></a>\n\n## #{label(e)}\n\n"
  sig<<"Primary construction: #{model_views.models.fetch(e['id']).first['label']}.\n\n"
  %w[order simple].each do |role|
    n=e.dig('roles',role,'declaration');s=statements.fetch(n)
    sig<<"### #{role.capitalize}\n\n[Compiled evidence](#{s[:path]}).\n\n```lean\n#{s[:text].rstrip}\n```\n\n"
  end
  e.dig('presentation','supplemental_statements').to_a.each do |ref|
    s=statements.fetch(ref.fetch('declaration'))
    audit=model_views.audit_link(ref.fetch('audit'),[ref.fetch('declaration')]).gsub('(../','(')
    sig<<"### #{ref.fetch('label')}\n\n[Compiled evidence](#{s[:path]}) · #{audit}.\n\n```lean\n#{s[:text].rstrip}\n```\n\n"
  end
  model_views.models.fetch(e['id']).reject { |m|m['default'] }.each do |m|
    sig<<"### #{m['label']}\n\n"
    if m['status']=='construction_complete'
      %w[order simple].each do |role|
        s=statements.fetch(m.dig('roles',role,'declaration'))
        sig<<"#{role.capitalize}: [compiled evidence](#{s[:path]}).\n\n```lean\n#{s[:text].rstrip}\n```\n\n"
      end
    else
      c=m.fetch('contract')
      sig<<"[Concrete-model Lean certificate](#{c['evidence']}/#{c['solution_file']}) · [exact mathematical specification](#{c['evidence']}/#{c['reference_file']}).\n\n"
    end
  end
  model_views.edges(e['id']).each { |c|sig<<model_views.certificate(c)+" · "+model_views.source(c['witness'])+".\n\n" }
end
out['THEOREM_STATEMENTS.md']=sig
out['catalogue/ISOMORPHISMS.md']=model_views.isomorphism_page(statements)
out['catalogue/current-verification.json']=JSON.pretty_generate({
  format:2,scope:'Current-source-bound compiled declaration audit; not a fresh full rebuild or independent replay',
  registry_sha256:Digest::SHA256.file('catalogue/catalogue.json').hexdigest,
  realizations_sha256:Digest::SHA256.file('catalogue/realizations.json').hexdigest,
  comparisons_sha256:Digest::SHA256.file('catalogue/comparisons.json').hexdigest,
  roots_sha256:Digest::SHA256.file('verification/roots.json').hexdigest,
  source_hashes_sha256:Digest::SHA256.file(current.fetch('sources')).hexdigest,
  completed_families:16,completed_sporadics:16,completed_exceptional:1,
  displayed_models:model_views.models.values.sum(&:size),multiple_model_entries:model_views.multiple.keys,
  construction_isomorphism_certificates:model_views.comparisons.map { |c|c.dig('witness','declaration') },
  checked_references:load_json('verification/roots.json').size,compiled_audit:audit,
  prior_catalogue_check:'verification/catalogue/2026-10-19/original-current-verification.json',
  publication_acceptance:'pending; see verification/current.json and AUDIT.md'
})+"\n"
out.each do |p,s|
  if mode=='refresh'
    File.write(p,s)
  else
    raise "Stale generated file: #{p}" unless File.file?(p) && File.read(p)==s
  end
end
puts "PASS: #{entries.size} entries, #{wanted.size} compiled signatures, #{comparison_rows.size} explicit comparison interfaces, 33 source-bound diagrams (#{mode})."

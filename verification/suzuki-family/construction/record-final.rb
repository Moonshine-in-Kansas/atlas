#!/usr/bin/env ruby
# Assemble already-passed Suzuki scopes and their exact compiled public statements.
# Does not build, commit or publish. Input: explicit six-scope run-path JSON.
require 'json'
require 'digest'
require 'fileutils'
require 'zlib'
require 'pathname'
abort 'Supply the six-scope run-path JSON' unless ARGV.size==1
paths=JSON.parse(File.read(ARGV[0]))
scopes=%w[structure order simplicity exception transport public]
abort 'Wrong scopes' unless paths.keys.sort==scopes.sort
read=->(p){File.file?(p) ? File.binread(p) : Zlib::GzipReader.open(p+'.gz',&:read).b}
sha=->(p){Digest::SHA256.hexdigest(read.call(p))}
paths.each do |scope,p|
  abort 'Unsafe path' unless p.start_with?('verification/runs/')&&Pathname.new(p).cleanpath.to_s==p
  r=JSON.parse(read.call(p+'/RESULT.json'))
  abort "Unpassed scope #{scope}" unless r['status']=='passed'&&r['mode']=='full'&&r['checkpoint']=="suzuki-family-#{scope}"
end
base='verification/suzuki-family/construction'
main=paths.fetch('public');snapshot=JSON.parse(read.call(main+'/SNAPSHOT.json'))
nodes=read.call(main+'/dependencies.jsonl').lines.map{|l|JSON.parse(l)}.to_h{|n|[n['name'],n]}
roots=read.call(main+'/declarations.jsonl').lines.map{|l|JSON.parse(l)['declaration']}
ref=lambda do |n,theorem=true|
  abort "Missing public root #{n}" unless roots.include?(n)
  node=nodes.fetch(n);abort "Not a theorem #{n}" if theorem&&node['kind']!='theorem'
  {'declaration'=>n,'source'=>node['module'].tr('.','/')+'.lean'}
end
ns='Atlas.SuzukiFamily.'
parameters='F finite of characteristic 2, q=|F|=2^(2m+1); simple family m>=1, hence q>=8'
formula='q^2 * (q^2+1) * (q-1)'
roles={'model'=>ref.call(ns+'Group',false),'finite'=>ref.call(ns+'finite_group'),
  'order'=>ref.call(ns+'card_group').merge('formula'=>formula),'simple'=>ref.call(ns+'simple_of_large'),
  'nonabelian'=>ref.call(ns+'noncommutative_of_large')}
labels={
 'theta_square'=>'The iterated Frobenius twist squares to the squaring map',
 'map_theta'=>'Every field isomorphism commutes with the chosen Tits twist',
 'embedding_injective'=>'The actual generated subgroup embeds in the retained Sp4 model',
 'generated_hasForm'=>'Every group matrix lies in one of the two explicit cells',
 'cellMap_bijective'=>'Unique disjoint two-cell parameters, proved before order or simplicity',
 'fixes_infinity_iff_short'=>'The full infinity stabilizer is exactly the root-by-torus cell',
 'fixes_two_iff_torus'=>'The two-base-point stabilizer is exactly the torus',
 'pointAction_faithful'=>'Faithfulness of the actual projective ovoid action',
 'pointAction_two_pretransitive'=>'Double transitivity on the actual ovoid',
 'pointAction_preprimitive'=>'Primitivity derived independently of full-group order',
 'card_pointSet'=>'The ovoid contains q^2+1 actual projective points',
 'card_rootSubgroup'=>'The root subgroup has order q^2',
 'card_torusSubgroup'=>'The split torus has order q-1',
 'card_borel'=>'The full point stabilizer has order q^2(q-1)',
 'borel_solvable'=>'The full point stabilizer is solvable',
 'borelProjection_ker_eq_root'=>'The stabilizer projection has exactly the root-group kernel',
 'borelProjection_section'=>'The torus section splits the stabilizer projection',
 'rootIntoBorel_injective'=>'The root-group map into the full stabilizer is injective',
 'perfect_of_large'=>'Perfectness for every m>=1 by torus commutators, a Weyl word and torus squares',
 'simple_iff'=>'Exact simplicity criterion: m>=1',
 'binary_not_simple'=>'The same binary generated model has order20 and is nonsimple',
 'fieldEquiv_embedding'=>'Field transport agrees with entrywise transport in Sp4'
}
props=labels.map{|n,d|ref.call(ns+n).merge('description'=>d)}
{'typeSuzuki_construction'=>'Complete public package for the actual matrix model',
 'exists_typeSuzuki'=>'Group existence retains an equivalence to the actual model',
 'typeSuzuki_prime_power'=>'Every m>=1 is realized over an actual characteristic-two finite field',
 'exists_typeSuzuki_parameter'=>'Canonical Galois-field witness with the displayed Suzuki order',
 'typeSuzuki_field_transport'=>'Actual group equivalence under a field isomorphism'}.each{|n,d|props<<ref.call('Atlas.'+n).merge('description'=>d)}
entry={'id'=>'family.Suzuki','label'=>'Suzuki (2B2)','kind'=>'family','audit_entry'=>'SuzukiLie',
 'proof_status'=>'construction_complete',
 'construction'=>'Actual subgroup of Sp4(F) generated by the explicit Tits-twisted root, torus and Weyl matrices',
 'parameters'=>parameters,'exceptions'=>'The same model at m=0 (q=2) has order20 and is nonsimple; simple_iff proves the exact range',
 'recognition'=>'Direct standard Suzuki matrix construction and faithful ovoid action; no abstract Chevalley theorem, CFSG or order recognition. Exceptional graph-field fixed-point characterization is not asserted',
 'attribution'=>'Explicit Suzuki matrices and Frobenius twist; unique two-cell decomposition; perfect faithful primitive action with solvable point stabilizer',
 'owner'=>'Gerald Höhn','upstream_status'=>'No upstream acceptance claimed','roles'=>roles,'properties'=>props,
 'evidence'=>'suzuki-family-v1','presentation'=>{'label'=>'²B₂(q)','parameters'=>'q=2^(2m+1), m>=1; simple for all public parameters','construction'=>'Four-dimensional Suzuki matrix group'}}
row={'entry'=>'SuzukiLie','kind'=>'family','checking'=>'checked: six separate full structure, order, simplicity, exception, transport and public audits',
 'parameters'=>parameters,'order'=>formula,'model'=>roles['model']['declaration'],'finiteness_theorem'=>roles['finite']['declaration'],
 'order_theorem'=>roles['order']['declaration'],'simplicity_theorem'=>roles['simple']['declaration'],'noncommutativity'=>roles['nonabelian']['declaration']}
scope=entry.slice('construction','parameters','exceptions','recognition','attribution')
inventory={'groups'=>[row],'properties'=>props.map{|p|p.merge('entry'=>'Atlas.SuzukiFamily')},'catalogue_scope'=>scope}
write=->(p,x){File.write(p,JSON.pretty_generate(x)+"\n")}
write.call(base+'/ENTRY.json',entry);write.call(base+'/INVENTORY.json',inventory)
write.call(base+'/RUN_PATHS.json',paths)
write.call(base+'/RUNS.json',paths.transform_values{|p|{'directory'=>p,'manifest_sha256'=>sha.call(p+'/SHA256SUMS')}})
File.binwrite(base+'/THEOREM_STATEMENTS.txt',read.call(main+'/statements.log'))
files=%w[ENTRY.json INVENTORY.json RUN_PATHS.json RUNS.json THEOREM_STATEMENTS.txt record-final.rb]
File.write(base+'/MANIFEST.sha256',files.map{|f|"#{sha.call(base+'/'+f)}  #{f}\n"}.join)
evidence={'format'=>'suzuki-family-v1','directory'=>base,'manifest'=>base+'/MANIFEST.sha256',
 'manifest_sha256'=>sha.call(base+'/MANIFEST.sha256'),'source_commit'=>snapshot.fetch('commit'),
 'toolchain'=>snapshot.fetch('toolchain'),'statements'=>base+'/THEOREM_STATEMENTS.txt'}
write.call(base+'/EVIDENCE.json',evidence)
j=JSON.parse(File.read('docs/catalogue/catalogue.json'))
j['entries'][j['entries'].index{|x|x['id']=='family.Suzuki'}]=entry
j['evidence']['suzuki-family-v1']=evidence
j['policy']['active_mathematical_job']='SUZUKI_FAMILY_FORMALIZATION_PROJECT.md — mathematics and separate audits complete; final catalogue integration'
write.call('docs/catalogue/catalogue.json',j)
puts "Recorded six scopes and #{props.size} structural/public properties"

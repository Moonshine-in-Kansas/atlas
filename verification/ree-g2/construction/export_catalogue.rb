#!/usr/bin/env ruby
# Bind the concrete family to independent full audits; copy compiled statements verbatim.
require 'json'
require 'digest'
require 'zlib'
base=File.dirname(__FILE__)
paths=JSON.parse(File.read(base+'/RUN_PATHS.json'))
abort 'Expected six independent scopes' unless paths.keys.sort==%w[comparison field order simplicity structure transport]
read=lambda{|p|File.file?(p) ? File.binread(p) : Zlib::GzipReader.open(p+'.gz',&:read)}
paths.each_value{|p|r=JSON.parse(read.call(p+'/RESULT.json'));abort "Unaccepted run #{p}" unless r['status']=='passed'&&r['mode']=='full'}
main=paths.fetch('structure');snap=JSON.parse(read.call(main+'/SNAPSHOT.json'))
nodes=read.call(main+'/dependencies.jsonl').lines.map{|l|JSON.parse(l)}.to_h{|n|[n.fetch('name'),n]}
ref=lambda{|n|r=nodes.fetch(n);{'declaration'=>n,'source'=>r.fetch('module').tr('.','/')+'.lean'}}
params='F finite of characteristic 3, q=|F|=3^(2m+1), m>=1; the public family starts at q=27'
formula='q^3 * (q^3+1) * (q-1)'
roles={'model'=>ref.call('Atlas.ReeG2.Model'),'finite'=>ref.call('Atlas.ReeG2.finite_model'),
 'order'=>ref.call('Atlas.ReeG2.order').merge('formula'=>formula),'simple'=>ref.call('Atlas.ReeG2.simple'),
 'nonabelian'=>ref.call('Atlas.ReeG2.model_noncommutative')}
props={
 'Atlas.ReeG2.perfect'=>'Perfectness of the actual generated matrix group for m>=1',
 'Atlas.ReeG2.pointAction_two_pretransitive'=>'Actual faithful projective action is doubly transitive on q^3+1 points',
 'Atlas.ReeG2.pointAction_preprimitive'=>'Primitivity proved without a group-order or simplicity theorem',
 'Atlas.ReeG2.pointAction_faithful'=>'Faithfulness proved using the exact full stabilizer, before simplicity',
 'Atlas.ReeG2.card_pointSet'=>'Actual Ree-Tits projective point count q^3+1',
 'Atlas.ReeG2.card_borel'=>'Root/torus Borel order q^3(q-1)',
 'Atlas.ReeG2.fixes_infinity_iff_mem_borel'=>'Full infinity stabilizer is exactly the constructed Borel subgroup',
 'Atlas.ReeG2.infinityStabilizer_eq_borel'=>'Exact stabilizer identity for the actual left action',
 'Atlas.ReeG2.g2Embedding_injective'=>'Injective structural homomorphism into the actual split-octonion G2 model; no order recognition',
 'Atlas.typeReeG2_construction'=>'Public construction package for the same Tits-twisted seven-dimensional matrix group',
 'Atlas.exists_typeReeG2'=>'Existence witnessed by the actual matrix model over a specified field',
 'Atlas.exists_typeReeG2_parameter'=>'A nonabelian finite simple group for every m>=1, with a concrete canonical-field witness',
 'Atlas.typeReeG2_field_transport'=>'Concrete MulEquiv under every field equivalence',
 'Atlas.ReeG2.Checks.order27'=>'Uniform order specialized to GaloisField 3 3',
 'Atlas.ReeG2.Checks.order243'=>'Uniform order specialized to GaloisField 3 5',
 'Atlas.ReeG2.Checks.order2187'=>'Uniform order specialized to GaloisField 3 7',
 'Atlas.ReeG2.Checks.simple27'=>'Uniform simplicity specialized to the actual field of order27',
 'Atlas.ReeG2.Checks.simple243'=>'Uniform simplicity specialized to the actual field of order243'
}.map{|n,d|abort "Not a theorem #{n}" unless nodes.fetch(n)['kind']=='theorem';ref.call(n).merge('description'=>d)}
entry={'id'=>'family.ReeG2','label'=>'Ree (2G2)','kind'=>'family','audit_entry'=>'ReeG2',
 'proof_status'=>'construction_complete','construction'=>'Actual subgroup of GL7(F) generated by the explicit Tits-twisted alpha, beta, gamma, torus and Weyl matrices',
 'parameters'=>params,'exceptions'=>'m=0 (q=3) is excluded from the public simple family; no low-parameter extension or PSL2(8) identification is certified here',
 'recognition'=>'Direct standard Ree matrix construction and explicit injective map into the existing split-octonion G2 model; no CFSG, abstract Chevalley/Ree theorem or order recognition',
 'attribution'=>'Explicit Ree matrices, Frobenius Tits twist, invariant exterior-square/cross-product geometry and soluble-stabilizer simplicity criterion',
 'owner'=>'Gerald Höhn','upstream_status'=>'No upstream acceptance claimed','roles'=>roles,'properties'=>props,'evidence'=>'ree-g2-family-v1',
 'presentation'=>{'label'=>'²G₂(q)','construction'=>'Tits-twisted seven-dimensional Ree matrix group','parameters'=>'q=3^(2m+1), m>=1; simple for all public parameters'}}
row={'entry'=>'ReeG2','kind'=>'family','checking'=>'checked: independent full field, structure, order, simplicity, transport and comparison audits',
 'parameters'=>params,'order'=>formula,'model'=>roles['model']['declaration'],'finiteness_theorem'=>roles['finite']['declaration'],
 'order_theorem'=>roles['order']['declaration'],'simplicity_theorem'=>roles['simple']['declaration'],'noncommutativity'=>roles['nonabelian']['declaration']}
inv={'groups'=>[row],'properties'=>props.map{|p|p.merge('entry'=>'Atlas.ReeG2')},
 'catalogue_scope'=>entry.slice('id','label','kind','audit_entry','proof_status','construction','parameters','exceptions')}
File.write(base+'/ENTRY.json',JSON.pretty_generate(entry)+"\n")
File.write(base+'/INVENTORY.json',JSON.pretty_generate(inv)+"\n")
File.write(base+'/RUNS.json',JSON.pretty_generate(paths.transform_values{|p|{'directory'=>p,'manifest_sha256'=>Digest::SHA256.file(p+'/SHA256SUMS').hexdigest}})+"\n")
statements=read.call(main+'/statements.log');File.binwrite(base+'/THEOREM_STATEMENTS.txt',statements)
Zlib::GzipWriter.open(base+'/THEOREM_STATEMENTS.txt.gz'){|g|g.mtime=0;g.write(statements)}
files=%w[ENTRY.json INVENTORY.json RUNS.json THEOREM_STATEMENTS.txt THEOREM_STATEMENTS.txt.gz]
File.write(base+'/MANIFEST.sha256',files.map{|n|"#{Digest::SHA256.file(base+'/'+n).hexdigest}  #{n}\n"}.join)
evidence={'format'=>'ree-g2-family-v1','directory'=>base,'manifest'=>base+'/MANIFEST.sha256',
 'manifest_sha256'=>Digest::SHA256.file(base+'/MANIFEST.sha256').hexdigest,
 'source_commit'=>snap['commit'],'toolchain'=>snap['toolchain'],'statements'=>base+'/THEOREM_STATEMENTS.txt.gz'}
File.write(base+'/EVIDENCE.json',JSON.pretty_generate(evidence)+"\n")
puts "Prepared one small Ree family and #{props.size} audited properties."
